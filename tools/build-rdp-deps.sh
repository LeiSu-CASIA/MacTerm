#!/bin/zsh
set -euo pipefail
cd "${0:A:h}/.."
ROOT="$PWD"
RDP_BASE="$ROOT/build/rdp-deps"
RDP_PREFIX="$RDP_BASE/prefix"
CMAKE="$ROOT/build/rdp-tools/bin/cmake"
mkdir -p "$RDP_BASE/openssl-build" "$RDP_PREFIX"
if [[ ! -f "$RDP_PREFIX/lib/libssl.a" ]]; then
 (
  cd "$RDP_BASE/openssl-build"
  /usr/bin/perl "$RDP_BASE/src/openssl-openssl-3.5.9/Configure" darwin64-arm64-cc --prefix="$RDP_PREFIX" --openssldir="$RDP_PREFIX/ssl" no-shared no-module no-tests no-apps -mmacosx-version-min=12.0
  /usr/bin/make -j4
  /usr/bin/make install_sw
 )
fi
"$CMAKE" -S "$RDP_BASE/src/cJSON-1.7.19" -B "$RDP_BASE/cjson-build" -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$RDP_PREFIX" -DCMAKE_OSX_DEPLOYMENT_TARGET=12.0 -DBUILD_SHARED_LIBS=OFF -DENABLE_CJSON_TEST=OFF -DENABLE_CJSON_UTILS=OFF
"$CMAKE" --build "$RDP_BASE/cjson-build" --parallel 4
"$CMAKE" --install "$RDP_BASE/cjson-build"
python3 tools/patch-rdp-clipboard.py
RDP_CHANNEL_FLAGS=()
for option_file in "$RDP_BASE/src/FreeRDP-3.33.0"/channels/*/ChannelOptions.cmake; do
 channel_name=${option_file:h:t}
 RDP_CHANNEL_FLAGS+=("-DCHANNEL_${(U)channel_name}=OFF")
done
"$CMAKE" -S "$RDP_BASE/src/FreeRDP-3.33.0" -B "$RDP_BASE/freerdp-build" \
 -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$RDP_PREFIX" -DCMAKE_PREFIX_PATH="$RDP_PREFIX" \
 -DCMAKE_OSX_DEPLOYMENT_TARGET=12.0 -DCMAKE_C_COMPILER=/usr/bin/clang -DCMAKE_CXX_COMPILER=/usr/bin/clang++ \
 -DCMAKE_EXPORT_NO_PACKAGE_REGISTRY=ON -DCMAKE_EXPORT_PACKAGE_REGISTRY=OFF -DUSE_VERSION_FROM_GIT_TAG=OFF -DUSE_GIT_FOR_REVISION=OFF -DBUILD_SHARED_LIBS=OFF -DBUILD_TESTING=OFF -DWITH_SAMPLE=OFF -DWITH_MANPAGES=OFF \
 -DOPENSSL_ROOT_DIR="$RDP_PREFIX" -DOPENSSL_USE_STATIC_LIBS=TRUE \
 -DOPENSSL_SSL_LIBRARY="$RDP_PREFIX/lib/libssl.a" -DOPENSSL_CRYPTO_LIBRARY="$RDP_PREFIX/lib/libcrypto.a" -DOPENSSL_INCLUDE_DIR="$RDP_PREFIX/include" \
 -DWITH_CLIENT_COMMON=ON -DWITH_CLIENT=OFF -DWITH_SERVER=ON -DWITH_SHADOW=OFF -DWITH_PROXY=OFF \
 -DWITH_CHANNELS=ON -DWITH_CLIENT_CHANNELS=ON -DWITH_SERVER_CHANNELS=ON "${RDP_CHANNEL_FLAGS[@]}" -DCHANNEL_CLIPRDR=ON -DCHANNEL_CLIPRDR_CLIENT=ON -DCHANNEL_CLIPRDR_SERVER=ON -DWITH_FFMPEG=OFF -DWITH_SWSCALE=OFF -DWITH_OPENH264=OFF \
 -DWITH_X11=OFF -DWITH_WAYLAND=OFF -DWITH_CLIENT_SDL=OFF -DWITH_CLIENT_MAC=OFF \
 -DWITH_CUPS=OFF -DWITH_PULSE=OFF -DWITH_ALSA=OFF -DWITH_MACAUDIO=OFF \
 -DWITH_PCSC=OFF -DWITH_PCSC_WINPR=OFF -DWITH_SMARTCARD_EMULATE=OFF -DWITH_SMARTCARD_INSPECT=OFF -DWITH_SMARTCARD_PCSC=OFF \
 -DWITH_UNICODE_BUILTIN=ON -DWITH_KRB5=OFF -DWITH_PKCS11=OFF -DWITH_FUSE=OFF -DWITH_WINPR_TOOLS=OFF -DWITH_CJSON_REQUIRED=ON
"$CMAKE" --build "$RDP_BASE/freerdp-build" --parallel 4
"$CMAKE" --install "$RDP_BASE/freerdp-build"
echo "RDP dependencies built in $RDP_PREFIX"
